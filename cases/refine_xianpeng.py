def set_para_text(para, text):
    """Replace all runs in a paragraph with a single run."""
    for run in para.runs:
        run.text = ''
    if para.runs:
        para.runs[0].text = text
    else:
        para.add_run(text)

def make_blue(para):
    """Color all runs in a paragraph blue."""
    for run in para.runs:
        run.font.color.rgb = BLUE

def set_and_blue(para, text):
    """Set paragraph text and color it blue."""
    set_para_text(para, text)
    make_blue(para)

